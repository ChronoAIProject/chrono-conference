/** Every full binary bracket string with n leaves, leaves written as '.', pairs as (xy). */
const shapeCache = new Map();
function brackets(n) {
  if (shapeCache.has(n)) return shapeCache.get(n);
  const out = n === 1 ? ['.'] : [];
  for (let k = 1; k < n; k++) for (const l of brackets(k)) for (const r of brackets(n - k)) out.push(`(${l}${r})`);
  shapeCache.set(n, out); return out;
}
const popcount = (x) => { let c = 0; while (x) { c += x & 1; x >>= 1; } return c; };
/** Fiber(a, b) as a set of strings: every shape, every placement of a α-leaves (bit masks over the leaves). */
function fiberSet(a, b) {
  const n = a + b, out = new Set();
  if (n < 1) return out;
  for (const sh of brackets(n)) for (let mask = 0; mask < 1 << n; mask++) {
    if (popcount(mask) !== a) continue;
    let i = 0; out.add(sh.replace(/\./g, () => ((mask >> i++) & 1 ? 'a' : 'b')));
  }
  return out;
}
