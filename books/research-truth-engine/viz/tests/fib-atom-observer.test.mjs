/** The additive subgroup of (ℤ/H)² generated by two vectors: a closure by breadth-first search from 0. */
function subgroup(g1, g2, H) {
  const seen = new Set([0]), queue = [[0, 0]];
  while (queue.length) {
    const [x, y] = queue.shift();
    for (const [dx, dy] of [g1, g2]) { const p = [md(x + dx, H), md(y + dy, H)], key = p[0] + H * p[1]; if (!seen.has(key)) { seen.add(key); queue.push(p); } }
  }
  return seen;
}
/** Pisano period: the least p ≥ 1 with F(p) ≡ 0 and F(p + 1) ≡ 1 mod H (that is, Mᵖ ≡ I). */
